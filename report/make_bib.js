'use strict';
// Writes report/generated/refs.tex (thebibliography, keys ref1..refN) from the deck's reference list,
// so the paper and the slides share one numbered, checked list.
const fs = require('fs');
const path = require('path');
const refs = require('../docs/mid_review/src/refs.js');

const esc = (s) => s.replace(/\\/g, '\\textbackslash{}').replace(/([&%$#_{}])/g, '\\$1').replace(/~/g, '\\textasciitilde{}')
  .replace(/–/g, '--').replace(/—/g, '---').replace(/×/g, '$\\times$');
const body = refs.map((r) => `\\bibitem{ref${r.n}} ${esc(r.text)} \\url{${r.url}}`).join('\n\n');
const out = path.join(__dirname, 'generated', 'refs.tex');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, `% generated by report/make_bib.js from docs/mid_review/src/refs.js; do not edit\n\\begin{thebibliography}{99}\n\\small\n${body}\n\\end{thebibliography}\n`);
console.log(`wrote ${out}: ${refs.length} references`);
